# STEP 3 — ROUTE EFFICIENCY SCORE BY SHIP MODE
# ════════════════════════════════════════════════════════════════

def step3_route_efficiency_by_mode(data: pd.DataFrame) -> pd.DataFrame:
    """Build the Route Efficiency Score distribution (%) for each Ship Mode."""
    print("\n" + "=" * 60)
    print("STEP 3: Route Efficiency Score by Ship Mode")
    print("=" * 60)

    if "Route Efficiency Score" not in data.columns:
        print("  Route Efficiency Score column not found - skipping.")
        return pd.DataFrame()

    counts = (
        data.groupby(["Ship Mode", "Route Efficiency Score"])
        .size()
        .unstack(fill_value=0)
    )
    pct = counts.div(counts.sum(axis=1), axis=0).mul(100).round(2).reset_index()

    save_summary(pct, "ship_mode_route_efficiency.csv")
    print(pct.to_string(index=False))

    return pct


