# STEP 20 — SHIP MODE RANKING
# ════════════════════════════════════════════════════════════════

def step20_ship_mode_ranking(summary: pd.DataFrame) -> pd.DataFrame:
    """
    Rank Ship Modes on Sales, Profit, Lead Time and Delay Rate, then
    derive an Overall Rank from the average of the individual ranks
    (lower Overall Rank = better all-round performance).
    """
    print("\n" + "=" * 60)
    print("STEP 20: Ship Mode Ranking")
    print("=" * 60)

    ranking = summary[["Ship Mode"]].copy()

    ranking["Sales Rank"] = summary["Total_Sales"].rank(ascending=False, method="min").astype(int)
    ranking["Profit Rank"] = summary["Total_Gross_Profit"].rank(ascending=False, method="min").astype(int)
    ranking["Lead Time Rank"] = summary["Average_Lead_Time"].rank(ascending=True, method="min").astype(int)

    if "Delay_Rate_%" in summary.columns:
        ranking["Delay Rank"] = summary["Delay_Rate_%"].rank(ascending=True, method="min").astype(int)
        rank_cols = ["Sales Rank", "Profit Rank", "Lead Time Rank", "Delay Rank"]
    else:
        rank_cols = ["Sales Rank", "Profit Rank", "Lead Time Rank"]

    ranking["Overall Rank"] = (
        ranking[rank_cols].mean(axis=1).rank(ascending=True, method="min").astype(int)
    )
    ranking = ranking.sort_values("Overall Rank").reset_index(drop=True)

    save_summary(ranking, "ship_mode_ranking.csv")
    print(ranking.to_string(index=False))

    top_mode = ranking.loc[ranking["Overall Rank"].idxmin(), "Ship Mode"]
    add_insight(f"Overall Best-Ranked Ship Mode (composite score): {top_mode}")

    return ranking


