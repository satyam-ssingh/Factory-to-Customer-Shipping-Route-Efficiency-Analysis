# STEP 22 — BUSINESS RECOMMENDATION ENGINE
# ════════════════════════════════════════════════════════════════

def step22_recommendation_engine(summary: pd.DataFrame,
                                  ranking: pd.DataFrame,
                                  risk_df: pd.DataFrame) -> str:
    """
    Automatically generate plain-language business recommendations
    based on the Ship Mode analysis (best/worst mode, delay reduction,
    profit improvement, route optimization).
    """
    print("\n" + "=" * 60)
    print("STEP 22: Business Recommendation Engine")
    print("=" * 60)

    recommendations = []

    try:
        if not ranking.empty:
            best_mode = ranking.iloc[0]["Ship Mode"]
            if "Delay Rank" in ranking.columns:
                worst_mode = ranking.sort_values(
                    ["Overall Rank", "Delay Rank"], ascending=[True, True]
                ).iloc[-1]["Ship Mode"]
            else:
                worst_mode = ranking.sort_values("Overall Rank", ascending=True).iloc[-1]["Ship Mode"]
            recommendations.append(
                f"1. Best Overall Ship Mode: '{best_mode}' delivers the strongest balance of "
                "sales, profit, speed and reliability. Prioritize this mode for high-value "
                "or time-sensitive shipments."
            )
            
            recommendations.append(
                f"2. Worst Overall Ship Mode: '{worst_mode}' ranks lowest across the composite "
                "KPI score. Review its cost structure, carrier performance, and routing logic."
            )

        if not risk_df.empty:
            high_risk_modes = risk_df.loc[risk_df["Delay Risk Score"] == "High", "Ship Mode"].tolist()
            if high_risk_modes:
                recommendations.append(
                    "3. Delay Reduction: " + ", ".join(high_risk_modes) +
                    " show High delay risk. Consider renegotiating carrier SLAs, adding buffer "
                    "capacity during peak periods, or shifting volume to faster alternatives."
                )
            else:
                recommendations.append(
                    "3. Delay Reduction: No Ship Mode currently falls into the High delay-risk "
                    "category; continue monitoring Delay Rate % monthly to catch early drift."
                )

        if "Average_Profit_Margin" in summary.columns:
            low_margin_row = summary.loc[summary["Average_Profit_Margin"].idxmin()]
            recommendations.append(
                f"4. Profit Improvement: '{low_margin_row['Ship Mode']}' has the lowest average "
                f"profit margin ({low_margin_row['Average_Profit_Margin']:.2f}%). Investigate "
                "cost-to-serve and consider targeted pricing or cost-reduction initiatives for "
                "this mode."
            )

        if "Average_Lead_Time" in summary.columns:
            slow_row = summary.loc[summary["Average_Lead_Time"].idxmax()]
            fast_row = summary.loc[summary["Average_Lead_Time"].idxmin()]
            recommendations.append(
                f"5. Route Optimization: '{slow_row['Ship Mode']}' has the longest average lead "
                f"time ({slow_row['Average_Lead_Time']:.2f} days) versus '{fast_row['Ship Mode']}' "
                f"at {fast_row['Average_Lead_Time']:.2f} days. Re-evaluate routing and carrier "
                "allocation on the slowest factory-to-state routes within this mode."
            )

        recommendations.append(
            "6. Capacity Planning: align fleet/carrier capacity with the highest-volume Ship "
            "Mode to avoid bottlenecks during demand spikes, while maintaining service levels "
            "on lower-volume, premium modes."
        )

    except Exception as exc:
        print(f"  WARNING: Recommendation generation encountered an issue: {exc}")

    report_text = "SHIP MODE BUSINESS RECOMMENDATIONS\n" + "=" * 60 + "\n\n"
    report_text += "\n\n".join(recommendations) + "\n"

    save_report_text(report_text, "ship_mode_recommendations.txt")
    for rec in recommendations:
        print(f"  {rec}\n")

    return report_text


