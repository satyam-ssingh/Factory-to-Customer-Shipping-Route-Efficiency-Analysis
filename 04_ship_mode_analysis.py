# STEP 2 — BUILD CORE SHIP MODE SUMMARY
# ════════════════════════════════════════════════════════════════

def step2_build_ship_mode_summary(data: pd.DataFrame) -> pd.DataFrame:
    """
    Calculate, per Ship Mode:
      Total Shipments, Total Sales, Total Gross Profit,
      Average Shipping Lead Time, Average Profit Margin,
      Delay Rate %, On-Time Rate %, Moderate Delay %, Delayed %.
    """
    print("\n" + "=" * 60)
    print("STEP 2: Ship Mode Summary Table")
    print("=" * 60)

    summary = (
        data.groupby("Ship Mode")
        .agg(
            Total_Shipments=("Order ID", "count"),
            Total_Sales=("Sales", "sum"),
            Total_Gross_Profit=("Gross Profit", "sum"),
            Average_Lead_Time=(LEAD_TIME_COL, "mean"),
            Average_Profit_Margin=("Profit Margin %", "mean"),
        )
        .round(2)
        .reset_index()
    )

    # ── Delay Status breakdown (On Time / Moderate Delay / Delayed) ──
    if "Delay Status" in data.columns:
        status_counts = (
            data.groupby(["Ship Mode", "Delay Status"])
            .size()
            .unstack(fill_value=0)
        )
        status_pct = status_counts.div(status_counts.sum(axis=1), axis=0).mul(100).round(2)

        for status in ["On Time", "Moderate Delay", "Delayed"]:
            if status not in status_pct.columns:
                status_pct[status] = 0.0

        status_pct = status_pct.rename(columns={
            "On Time": "On_Time_Rate_%",
            "Moderate Delay": "Moderate_Delay_%",
            "Delayed": "Delay_Rate_%",
        }).reset_index()

        summary = summary.merge(
            status_pct[["Ship Mode", "On_Time_Rate_%", "Moderate_Delay_%", "Delay_Rate_%"]],
            on="Ship Mode", how="left",
        )
    else:
        summary["On_Time_Rate_%"] = np.nan
        summary["Moderate_Delay_%"] = np.nan
        summary["Delay_Rate_%"] = np.nan

    summary = summary.fillna(0)

    # Order rows logically: Same Day -> First -> Second -> Standard
    summary["Ship Mode"] = pd.Categorical(
        summary["Ship Mode"], categories=order_ship_modes(summary["Ship Mode"]), ordered=True
    )
    summary = summary.sort_values("Ship Mode").reset_index(drop=True)

    save_summary(summary, "ship_mode_summary.csv")
    print(summary.to_string(index=False))

    return summary


