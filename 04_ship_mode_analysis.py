# STEP 17 — OUTLIER DETECTION (IQR METHOD)
# ════════════════════════════════════════════════════════════════

def step17_outlier_detection(data: pd.DataFrame) -> pd.DataFrame:
    """
    Detect outliers using the IQR method (1.5x IQR fences) for
    Sales, Gross Profit and Shipping Lead Time (Simulated), and
    report the outlier count/percentage per Ship Mode.
    """
    print("\n" + "=" * 60)
    print("STEP 17: Outlier Detection (IQR Method)")
    print("=" * 60)

    target_cols = ["Sales", "Gross Profit", LEAD_TIME_COL]
    target_cols = [c for c in target_cols if c in data.columns]

    if not target_cols:
        print("  WARNING: None of the target outlier columns were found.")
        return pd.DataFrame()

    outlier_rows = []
    for col in target_cols:
        series = pd.to_numeric(data[col], errors="coerce")
        q1, q3 = series.quantile([0.25, 0.75])
        iqr = q3 - q1
        lower_fence = q1 - 1.5 * iqr
        upper_fence = q3 + 1.5 * iqr
        is_outlier = (series < lower_fence) | (series > upper_fence)

        temp = data.loc[series.notna()].copy()
        temp["__is_outlier__"] = is_outlier.loc[series.notna()]

        for ship_mode, group in temp.groupby("Ship Mode"):
            total = len(group)
            outliers = int(group["__is_outlier__"].sum())
            outlier_rows.append({
                "Ship Mode": ship_mode,
                "Column": col,
                "Lower Fence": round(lower_fence, 2),
                "Upper Fence": round(upper_fence, 2),
                "Total Records": total,
                "Outlier Count": outliers,
                "Outlier %": round(outliers / total * 100, 2) if total else 0.0,
            })

    outliers_df = pd.DataFrame(outlier_rows)
    outliers_df["Ship Mode"] = pd.Categorical(
        outliers_df["Ship Mode"], categories=order_ship_modes(outliers_df["Ship Mode"]), ordered=True
    )
    outliers_df = outliers_df.sort_values(["Column", "Ship Mode"]).reset_index(drop=True)

    save_summary(outliers_df, "ship_mode_outliers.csv")
    print(outliers_df.to_string(index=False))

    return outliers_df


