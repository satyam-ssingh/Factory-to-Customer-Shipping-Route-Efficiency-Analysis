def save_chart(filename: str) -> None:
    """Save current matplotlib figure to EDA_Charts/ and close it."""
    global chart_count
    path = os.path.join(CHARTS_DIR, filename)
    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches="tight")
    plt.close()
    chart_count += 1
    print(f"  [Chart saved] {path}")


def save_summary(data: pd.DataFrame, filename: str) -> None:
    """Save a DataFrame to EDA_Summaries/ as CSV."""
    global summary_count
    path = os.path.join(SUMMARIES_DIR, filename)
    data.to_csv(path, index=False, float_format="%.2f")
    summary_count += 1
    print(f"  [Summary saved] {path}")


def save_report_text(text: str, filename: str) -> None:
    """Save a plain-text business/executive report to EDA_Summaries/."""
    global report_count
    path = os.path.join(SUMMARIES_DIR, filename)
    try:
        with open(path, "w", encoding="utf-8") as report_file:
            report_file.write(text)
        report_count += 1
        print(f"  [Report saved] {path}")
    except OSError as exc:
        print(f"  WARNING: Failed to save report '{filename}': {exc}")


def add_insight(text: str) -> None:
    """Append a business insight to the global list and print it."""
    insight_list.append(text)
    print(f"  [Insight {len(insight_list):02d}] {text}")


def fmt_currency(val: float) -> str:
    """Format a float as $X,XXX.XX."""
    return f"${val:,.2f}"


def order_ship_modes(values) -> list:
    """Return ship mode values ordered Same Day -> Standard Class,
    keeping any unexpected categories at the end."""
    values = list(values)  # avoid pandas Series "in" matching on index
    known = [m for m in SHIP_MODE_ORDER if m in values]
    extra = [m for m in values if m not in SHIP_MODE_ORDER]
    return known + extra


