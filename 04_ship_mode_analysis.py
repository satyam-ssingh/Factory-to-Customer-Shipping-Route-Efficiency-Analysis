def step4_comparison_table(summary: pd.DataFrame, efficiency: pd.DataFrame) -> pd.DataFrame:
    """Combine core KPIs with Route Efficiency Score distribution for an
    at-a-glance comparison table across all Ship Modes."""
    print("\n" + "=" * 60)
