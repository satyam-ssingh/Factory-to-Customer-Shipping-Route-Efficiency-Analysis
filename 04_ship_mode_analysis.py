# STEP 7 — VISUALIZATION: DELAY STATUS (STACKED BAR CHART)
# ════════════════════════════════════════════════════════════════

def step7_chart_delay_stacked(data: pd.DataFrame) -> None:
    """Stacked bar chart of Delay Status counts by Ship Mode."""
    print("\n" + "=" * 60)
    print("STEP 7: Chart - Delay Status (Stacked Bar)")
    print("=" * 60)

    if "Delay Status" not in data.columns:
        print("  Delay Status column not found - skipping.")
        return

    pivot = (
        data.groupby(["Ship Mode", "Delay Status"])
        .size()
        .unstack(fill_value=0)
        .reindex(order_ship_modes(data["Ship Mode"].unique()))
    )

    status_colors = {
        "On Time": "#2ECC71",
        "Moderate Delay": "#F1C40F",
        "Delayed": "#E74C3C",
    }
    colors = [status_colors.get(c, "#95A5A6") for c in pivot.columns]

    ax = pivot.plot(
        kind="bar", stacked=True, color=colors,
        figsize=(11, 6), edgecolor="white",
    )
    ax.set_title("Delay Status Distribution by Ship Mode", fontweight="bold")
    ax.set_xlabel("Ship Mode")
    ax.set_ylabel("Order Count")
    ax.tick_params(axis="x", rotation=20)
    ax.legend(title="Delay Status")

    save_chart("04_shipmode_delay_stacked.png")


