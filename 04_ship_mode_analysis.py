# STEP 19 — DELAY RISK SCORE
# ════════════════════════════════════════════════════════════════

def step19_delay_risk_score(summary: pd.DataFrame) -> pd.DataFrame:
    """
    Classify each Ship Mode into a Delay Risk category (Low / Medium /
    High) based on its Delay Rate (%).

    Thresholds: < 15% -> Low, 15-35% -> Medium, > 35% -> High.
    """
    print("\n" + "=" * 60)
    print("STEP 19: Delay Risk Score")
    print("=" * 60)

    if "Delay_Rate_%" not in summary.columns:
        print("  WARNING: Delay_Rate_% column not found - skipping.")
        return pd.DataFrame()

    def classify_risk(delay_rate: float) -> str:
        if pd.isna(delay_rate):
            return "Unknown"
        if delay_rate < 15:
            return "Low"
        if delay_rate <= 35:
            return "Medium"
        return "High"

    risk_df = summary[["Ship Mode", "Delay_Rate_%"]].copy()
    risk_df["Delay Risk Score"] = risk_df["Delay_Rate_%"].apply(classify_risk)
    risk_df = risk_df.sort_values("Delay_Rate_%", ascending=False).reset_index(drop=True)

    save_summary(risk_df, "delay_risk_summary.csv")
    print(risk_df.to_string(index=False))

    high_risk = risk_df.loc[risk_df["Delay Risk Score"] == "High", "Ship Mode"].tolist()
    if high_risk:
        add_insight(f"High Delay Risk Ship Mode(s): {', '.join(high_risk)}")

    return risk_df


