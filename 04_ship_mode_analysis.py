# STEP 21 — CONSOLIDATED KPI SUMMARY TABLE
# ════════════════════════════════════════════════════════════════

def step21_kpi_summary(summary: pd.DataFrame,
                        efficiency: pd.DataFrame,
                        ranking: pd.DataFrame) -> pd.DataFrame:
    """
    Build a single consolidated KPI table containing Ship Mode,
    Total Shipments, Total Sales, Total Gross Profit, Average Lead
    Time, Average Profit Margin, Delay Rate, Route Efficiency and
    Overall Rank.
    """
    print("\n" + "=" * 60)
    print("STEP 21: Consolidated KPI Summary Table")
    print("=" * 60)

    kpi = summary[[
        "Ship Mode", "Total_Shipments", "Total_Sales", "Total_Gross_Profit",
        "Average_Lead_Time", "Average_Profit_Margin",
    ]].copy()

    if "Delay_Rate_%" in summary.columns:
        kpi = kpi.merge(summary[["Ship Mode", "Delay_Rate_%"]], on="Ship Mode", how="left")
    else:
        kpi["Delay_Rate_%"] = np.nan

    # Route Efficiency: % of shipments classified as "Excellent" or "Good"
    if not efficiency.empty:
        good_cols = [c for c in ["Excellent", "Good"] if c in efficiency.columns]
        if good_cols:
            eff_score = efficiency[["Ship Mode"] + good_cols].copy()
            eff_score["Route_Efficiency_%"] = eff_score[good_cols].sum(axis=1).round(2)
            kpi = kpi.merge(eff_score[["Ship Mode", "Route_Efficiency_%"]], on="Ship Mode", how="left")
        else:
            kpi["Route_Efficiency_%"] = np.nan
    else:
        kpi["Route_Efficiency_%"] = np.nan

    if not ranking.empty:
        kpi = kpi.merge(ranking[["Ship Mode", "Overall Rank"]], on="Ship Mode", how="left")
    else:
        kpi["Overall Rank"] = np.nan

    kpi = kpi.rename(columns={
        "Total_Shipments": "Total Shipments",
        "Total_Sales": "Total Sales",
        "Total_Gross_Profit": "Total Gross Profit",
        "Average_Lead_Time": "Average Lead Time",
        "Average_Profit_Margin": "Average Profit Margin",
        "Delay_Rate_%": "Delay Rate %",
        "Route_Efficiency_%": "Route Efficiency %",
    })

    kpi = kpi.sort_values("Overall Rank").reset_index(drop=True)

    save_summary(kpi, "ship_mode_kpi_summary.csv")
    print(kpi.to_string(index=False))

    return kpi


