# STEP 18 — ANOVA TEST
# ════════════════════════════════════════════════════════════════

def step18_anova_test(data: pd.DataFrame) -> pd.DataFrame:
    """
    Perform a one-way ANOVA test to determine whether Ship Mode has
    a statistically significant effect on Sales, Gross Profit and
    Shipping Lead Time (Simulated).
    """
    print("\n" + "=" * 60)
    print("STEP 18: ANOVA Test (Ship Mode Effect)")
    print("=" * 60)

    target_cols = ["Sales", "Gross Profit", LEAD_TIME_COL]
    target_cols = [c for c in target_cols if c in data.columns]

    anova_rows = []
    for col in target_cols:
        try:
            groups = [
                pd.to_numeric(group[col], errors="coerce").dropna()
                for _, group in data.groupby("Ship Mode")
            ]
            groups = [g for g in groups if len(g) > 1]

            if len(groups) < 2:
                print(f"  WARNING: Not enough groups to run ANOVA for '{col}'.")
                continue

            f_stat, p_value = stats.f_oneway(*groups)
            significant = "Yes" if p_value < 0.05 else "No"

            anova_rows.append({
                "Metric": col,
                "F-Statistic": round(f_stat, 4),
                "P-Value": round(p_value, 6),
                "Significant (p<0.05)": significant,
            })
        except Exception as exc:
            print(f"  WARNING: ANOVA failed for '{col}': {exc}")

    anova_df = pd.DataFrame(anova_rows)
    save_summary(anova_df, "anova_results.csv")
    print(anova_df.to_string(index=False))

    for _, row in anova_df.iterrows():
        add_insight(
            f"ANOVA on {row['Metric']}: F={row['F-Statistic']}, "
            f"p={row['P-Value']} -> Ship Mode effect significant: "
            f"{row['Significant (p<0.05)']}"
        )

    return anova_df


