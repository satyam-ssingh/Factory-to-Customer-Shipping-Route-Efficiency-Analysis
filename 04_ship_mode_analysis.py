# STEP 13 — BUSINESS INSIGHTS & CONSOLE REPORT
# ════════════════════════════════════════════════════════════════

def step13_business_report(summary: pd.DataFrame) -> None:
    """Print a professional console report highlighting the best, fastest,
    most profitable and lowest-delay Ship Modes, plus key business insights."""
    print("\n" + "=" * 60)
    print("STEP 13: Ship Mode Performance Report")
    print("=" * 60)

    # ── Best Ship Mode (highest total sales) ─────────────────
    best_sales_row = summary.loc[summary["Total_Sales"].idxmax()]
    add_insight(
        f"Best Ship Mode by Sales: {best_sales_row['Ship Mode']} "
        f"({fmt_currency(best_sales_row['Total_Sales'])})"
    )

    # ── Fastest Ship Mode (lowest average lead time) ─────────
    fastest_row = summary.loc[summary["Average_Lead_Time"].idxmin()]
    add_insight(
        f"Fastest Ship Mode: {fastest_row['Ship Mode']} "
        f"({fastest_row['Average_Lead_Time']:.2f} days average lead time)"
    )

    # ── Highest Profit Ship Mode ──────────────────────────────
    profit_row = summary.loc[summary["Total_Gross_Profit"].idxmax()]
    add_insight(
        f"Highest Profit Ship Mode: {profit_row['Ship Mode']} "
        f"({fmt_currency(profit_row['Total_Gross_Profit'])})"
    )

    # ── Lowest Delay Ship Mode ────────────────────────────────
    if "Delay_Rate_%" in summary.columns:
        lowest_delay_row = summary.loc[summary["Delay_Rate_%"].idxmin()]
        add_insight(
            f"Lowest Delay Ship Mode: {lowest_delay_row['Ship Mode']} "
            f"({lowest_delay_row['Delay_Rate_%']:.2f}% delayed)"
        )
        highest_delay_row = summary.loc[summary["Delay_Rate_%"].idxmax()]
        add_insight(
            f"Highest Delay Ship Mode: {highest_delay_row['Ship Mode']} "
            f"({highest_delay_row['Delay_Rate_%']:.2f}% delayed)"
        )

    # ── Most used Ship Mode ───────────────────────────────────
    volume_row = summary.loc[summary["Total_Shipments"].idxmax()]
    total_shipments = summary["Total_Shipments"].sum()
    add_insight(
        f"Most Used Ship Mode: {volume_row['Ship Mode']} "
        f"({int(volume_row['Total_Shipments']):,} shipments = "
        f"{volume_row['Total_Shipments'] / total_shipments * 100:.1f}% of all orders)"
    )

    # ── Margin comparison ──────────────────────────────────────
    margin_row = summary.loc[summary["Average_Profit_Margin"].idxmax()]
    add_insight(
        f"Highest Average Profit Margin: {margin_row['Ship Mode']} "
        f"({margin_row['Average_Profit_Margin']:.2f}%)"
    )

    # ── On-time performance ─────────────────────────────────────
    if "On_Time_Rate_%" in summary.columns:
        ontime_row = summary.loc[summary["On_Time_Rate_%"].idxmax()]
        add_insight(
            f"Best On-Time Rate: {ontime_row['Ship Mode']} "
            f"({ontime_row['On_Time_Rate_%']:.2f}% on time)"
        )

    # ── Speed vs cost trade-off note ────────────────────────────
    if fastest_row["Ship Mode"] != best_sales_row["Ship Mode"]:
        add_insight(
            f"Trade-off identified: {fastest_row['Ship Mode']} is fastest, "
            f"while {best_sales_row['Ship Mode']} drives the most sales volume "
            "- indicating a speed vs. revenue concentration trade-off."
        )

    # ── Final formatted report block ────────────────────────────
    print("\n" + "-" * 60)
    print("EXECUTIVE SHIP MODE REPORT")
    print("-" * 60)
    print(f"  Best Ship Mode (Sales)        : {best_sales_row['Ship Mode']}")
    print(f"  Fastest Ship Mode             : {fastest_row['Ship Mode']}")
    print(f"  Highest Profit Ship Mode      : {profit_row['Ship Mode']}")
    if "Delay_Rate_%" in summary.columns:
        print(f"  Lowest Delay Ship Mode        : {lowest_delay_row['Ship Mode']}")
    print(f"  Most Used Ship Mode           : {volume_row['Ship Mode']}")
    print("-" * 60)

    insights_df = pd.DataFrame({
        "Insight #": range(1, len(insight_list) + 1),
        "Insight": insight_list,
    })
    save_summary(insights_df, "ship_mode_business_insights.csv")


