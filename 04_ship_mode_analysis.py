# STEP 16 — STATISTICAL SUMMARY
# ════════════════════════════════════════════════════════════════

def step16_statistical_summary(data: pd.DataFrame) -> pd.DataFrame:
    """
    Compute Mean, Median, Std Dev, Min, Max, Q1, Q3 for Sales,
    Gross Profit and Shipping Lead Time (Simulated), broken down
    by Ship Mode.
    """
    print("\n" + "=" * 60)
    print("STEP 16: Statistical Summary")
    print("=" * 60)

    target_cols = ["Sales", "Gross Profit", LEAD_TIME_COL]
    target_cols = [c for c in target_cols if c in data.columns]

    if not target_cols:
        print("  WARNING: None of the target statistical columns were found.")
        return pd.DataFrame()

    stats_rows = []
    for ship_mode, group in data.groupby("Ship Mode"):
        for col in target_cols:
            series = pd.to_numeric(group[col], errors="coerce").dropna()
            if series.empty:
                continue
            q1, q3 = series.quantile([0.25, 0.75])
            stats_rows.append({
                "Ship Mode": ship_mode,
                "Metric": col,
                "Mean": round(series.mean(), 2),
                "Median": round(series.median(), 2),
                "Std Dev": round(series.std(), 2),
                "Min": round(series.min(), 2),
                "Max": round(series.max(), 2),
                "Q1": round(q1, 2),
                "Q3": round(q3, 2),
            })

    stats_df = pd.DataFrame(stats_rows)
    stats_df["Ship Mode"] = pd.Categorical(
        stats_df["Ship Mode"], categories=order_ship_modes(stats_df["Ship Mode"]), ordered=True
    )
    stats_df = stats_df.sort_values(["Ship Mode", "Metric"]).reset_index(drop=True)

    save_summary(stats_df, "ship_mode_statistics.csv")
    print(stats_df.to_string(index=False))

    return stats_df


